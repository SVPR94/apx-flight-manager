/// default ../apx next to this repository.
library;

import 'dart:io';

void main(List<String> args) {
  final repo = File(Platform.script.toFilePath()).parent.parent.parent.parent;
  final apx = args.isNotEmpty ? args.first : (Platform.environment['APX_ROOT'] ?? '${repo.parent.path}/apx');
  final src = File('$apx/modules/params/param_manager.cpp');
  if (!src.existsSync()) {
    stderr.writeln('Not found: ${src.path} (pass the APX repository path or set APX_ROOT)');
    exit(2);
  }
  final text = src.readAsStringSync();
  final params = <String, (bool, String, String, String, String)>{};

  num value(String v) {
    final t = v.trim().replaceAll(RegExp(r'f$'), '');
    return t.startsWith('0x') ? int.parse(t.substring(2), radix: 16) : num.parse(t);
  }

  void add(String kind, String name, String def, String min, String max, String desc) {
    params[name] = (kind == 'i', '${value(def)}', '${value(min)}', '${value(max)}', desc);
  }

  // Plain entries: add_i("NAME", def, min, max, "desc") — may span lines.
  final plain = RegExp(r'add_([if])\(\s*"([A-Z0-9_]+)"\s*,\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*"([^"]*)"\s*\)', multiLine: true);
  for (final m in plain.allMatches(text)) {
    add(m[1]!, m[2]!, m[3]!, m[4]!, m[5]!, m[6]!);
  }
  // Loops: for (int ch = A; ch <= B; ++ch) { snprintf(name, …, "FMT", ch); add_x(name, …) … }
  final loop = RegExp(r'for \(int ch = (\d+); ch <= (\d+); \+\+ch\) \{(.*?)\n    \}', dotAll: true);
  final inner = RegExp(r'snprintf\(name, sizeof\(name\), "([^"]+)", ch\);\s*add_([if])\(name,\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*"([^"]*)"\)');
  for (final l in loop.allMatches(text)) {
    for (var ch = int.parse(l[1]!); ch <= int.parse(l[2]!); ch++) {
      for (final m in inner.allMatches(l[3]!)) {
        // SERVOn_FUNCTION defaults are expressions (32 + ch).
        final def = m[3]!.trim() == '32 + ch' ? '${32 + ch}' : m[3]!;
        add(m[2]!, m[1]!.replaceAll('%d', '$ch'), def, m[4]!, m[5]!, m[6]!);
      }
    }
  }

  String q(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/param_meta_gen from APX modules/params/param_manager.cpp. Do not edit.')
    ..writeln('// ${params.length} parameters.')
    ..writeln()
    ..writeln("import 'param_meta.dart';")
    ..writeln()
    ..writeln('const apxParamMeta = <String, ParamMeta>{');
  for (final e in (params.entries.toList()..sort((a, b) => a.key.compareTo(b.key)))) {
    final (isInt, def, min, max, desc) = e.value;
    b.writeln('  ${q(e.key)}: ParamMeta(${q(e.key)}, $isInt, $def, $min, $max, ${q(desc)}),');
  }
  b.writeln('};');
  final out = File('${repo.path}/packages/apx_vehicle/lib/src/param_meta.g.dart')..writeAsStringSync(b.toString());
  stdout.writeln('Wrote ${params.length} parameters to ${out.path}');
}
